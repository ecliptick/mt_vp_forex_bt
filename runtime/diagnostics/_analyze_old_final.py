"""FINAL ANALYSIS of the OLD repo's result.

  A. Buy-and-hold gold over the SAME window, same notional — is the
     strategy just a long bet?
  B. Lead buckets: entries that landed far BEFORE their zone's inversion
     are the look-ahead population. What do they earn?
  C. Restate with LIVE costs + realistic slippage.

NOTE: this module reads an EXTERNAL parquet and a generated report
artifact, so its body lives under a main guard -- importing it must not
read 4M bars or require the upstream repo to exist.
"""
import json
from pathlib import Path
import numpy as np
import pandas as pd


def main() -> None:
    P = Path(__file__).parent / "_reports" / "old_repo_decomposition.json"
    d = json.loads(P.read_text(encoding="utf-8"))
    tr = d["trades"]
    g = np.array([t["gross"] for t in tr])
    dr = np.array([t["drift"] for t in tr])

    print("=" * 76)
    print("A. BUY-AND-HOLD GOLD, same window, same notional ($3,000 = 1 oz)")
    print("=" * 76)
    df = pd.read_parquet(Path(r"C:\coding\ict_tier_v2\data\XAUUSD_S1_2025Q1.parquet"))
    close = df["close"].to_numpy(float)
    first, last = close[0], close[-1]
    print("  Q1 2025 gold: $%.2f -> $%.2f" % (first, last))
    print("  1 oz buy-and-hold P&L       = $%+.2f" % (last - first))
    print("  strategy gross (113 legs)   = $%+.2f" % g.sum())
    print("  strategy drift (passive)    = $%+.2f" % dr.sum())
    ts = pd.to_datetime(df["time"], utc=True)
    mo = ts.dt.strftime("%Y-%m").to_numpy()
    print("\n  monthly buy-and-hold (1 oz):")
    for m in sorted(set(mo)):
        idx = np.where(mo == m)[0]
        print("    %s  $%8.2f -> $%8.2f   B&H $%+8.2f"
              % (m, close[idx[0]], close[idx[-1]], close[idx[-1]] - close[idx[0]]))

    print("\n" + "=" * 76)
    print("B. LEAD BUCKETS — entry_bar vs the zone's true inverted_bar")
    print("=" * 76)

    # ⚠️ ``inverted_bar`` is NOT written by ``_probe_old_decomp.py`` — the
    # generator records only the trade fields, so a freshly-generated
    # artifact has no such key. This module therefore failed to IMPORT
    # (``KeyError: 'inverted_bar'`` at module scope), which broke
    # ``tests/test_no_dead_imports.py::test_every_module_imports_cleanly``.
    #
    # The analysis is a HISTORICAL look-ahead diagnostic. It is skipped
    # cleanly when the field is absent, rather than crashing the import.
    # The artifact is re-generated by ``_probe_old_decomp.py``, which is
    # the script that would have to add the field.
    if not tr or "inverted_bar" not in tr[0]:
        print("  SKIPPED: the artifact has no 'inverted_bar' field.")
        print("  (the generator _probe_old_decomp.py does not write it —")
        print("   this analysis needs a look-ahead artifact it never got.)")
        lead = np.zeros(len(tr), dtype=np.int64)
        _HAS_LEAD = False
    else:
        _HAS_LEAD = True
        lead = np.array([t["inverted_bar"] - t["entry_bar"] for t in tr])

    if _HAS_LEAD:
        buckets = [(-10**9, -100, "entry >100 bars BEFORE inversion"),
                   (-100, -10, "entry 10-100 bars BEFORE inversion"),
                   (-10, 0, "entry 0-10 bars BEFORE inversion"),
                   (0, 10**9, "entry AT/AFTER inversion (causal)")]
        for lo, hi, lab in buckets:
            m = (lead >= lo) & (lead < hi)
            if m.sum() == 0:
                print("  %-40s n=0" % lab)
                continue
            print("  %-40s n=%3d  gross $%8.2f  drift $%8.2f  excess $%8.2f"
                  % (lab, m.sum(), g[m].sum(), dr[m].sum(), (g - dr)[m].sum()))
        look = lead < -100
        print("\n  LOOK-AHEAD population (entry >100 bars before the "
              "inversion): n=%d" % look.sum())
        if look.sum():
            print("    their gross $%.2f  (%.1f%% of total gross)"
                  % (g[look].sum(), 100.0 * g[look].sum() / g.sum()))
            print("    their excess $%.2f" % (g - dr)[look].sum())

    print("\n" + "=" * 76)
    print("C. LIVE COSTS")
    print("=" * 76)
    qty = np.array([t["qty"] for t in tr])
    for lab, spr, slip in (("backtest model  ($0.19/oz, 0 slip)", 0.19, 0.0),
                            ("live spread     ($0.40/oz, 0 slip)", 0.40, 0.0),
                            ("live + 1 tick   ($0.40/oz, $0.05 x2)", 0.40, 0.05),
                            ("live + 2 ticks  ($0.40/oz, $0.10 x2)", 0.40, 0.10),
                            ("live + 4 ticks  ($0.40/oz, $0.20 x2)", 0.40, 0.20)):
        fee = float((qty * spr + 0.01 * 7.0).sum())
        drag = float((2 * slip * qty).sum())
        print("  %-36s fee $%7.2f  slip $%6.2f   NET $%+8.2f"
              % (lab, fee, drag, g.sum() - fee - drag))

    print("\n" + "=" * 76)
    print("D. THE GEOMETRY THAT MAKES IT WORK")
    print("=" * 76)
    print("  avg loss  $%.3f   avg win $%.2f   payoff %.1f:1   hit %.1f%%"
          % (-g[g <= 0].mean(), g[g > 0].mean(),
             g[g > 0].mean() / -g[g <= 0].mean(), 100.0 * (g > 0).mean()))
    pbe = -g[g <= 0].mean() / (g[g > 0].mean() - g[g <= 0].mean())
    print("  break-even hit rate = %.1f%%   actual = %.1f%%   edge = %+.1fpp"
          % (100 * pbe, 100 * (g > 0).mean(), 100 * ((g > 0).mean() - pbe)))
    print("  gross/leg $%.4f   vs our repo's live round trip $%.4f"
          % (g.mean(), 0.5029))
    print("  gross/leg / round-trip = %.2fx" % (g.mean() / 0.5029))


if __name__ == "__main__":
    main()
